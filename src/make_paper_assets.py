"""Generate the LaTeX artefacts that depend on the certified result data.

Outputs (auto-generated, deterministic; do not hand-edit):
  paper/tables_auto.tex       defines \\nmaxverified (loaded in the preamble,
                              before the abstract uses it)
  paper/tables_auto_body.tex  the \\input body of Table tab:results
  paper/fig_n9.tex            the tikzpicture for figure fig:figN9

Data conventions.
  results/dims_2_16.json  (list format) is the source of record for n=2..16;
  its bases are board cells (r,c).  Bases are converted with the canonical
  structure.to_uv, the exact function used by the structural oracle and the
  fast ladder, so the figure coordinates and the stored data cannot drift.
  Fast-ladder outputs (dims_fast_test2.json, dims_17_24.json; dict format,
  bases already in (u,v)) extend the dictionary for n outside that range.

Run:  python src/make_paper_assets.py
"""
from pathlib import Path
import json
import sys

from bishop import Cell                      # noqa: E402
from conjecture_check import conjectures     # noqa: E402
from structure import component_uv, to_uv    # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "results"
PAPER = ROOT / "paper"

sys.path.insert(0, str(Path(__file__).resolve().parent))

HEADER = "% AUTO-GENERATED by src/make_paper_assets.py -- do not edit.\n"

# The figure caption in main.tex names these nine (u,v) coordinates; the
# generator refuses to emit a figure whose optimum disagrees with the caption.
FIG_N9_LANDMARKS = sorted(
    [(0, 0), (-1, 1), (-2, 2), (-4, 4), (-3, 5), (2, 3), (3, 3), (1, 6), (1, 7)]
)


def load_results():
    """n -> {'even': (dim, [(u,v), ...]), 'odd': (dim, [(u,v), ...])}."""
    merged = {}
    recs = json.loads((RES / "dims_2_16.json").read_text())
    assert isinstance(recs, list) and recs[0]["n"] == 2, "unexpected format"
    for rec in recs:
        n = rec["n"]
        merged[n] = {
            "even": (rec["dim_even"], _rc_to_uv(rec["basis_even"], "even")),
            "odd": (rec["dim_odd"], _rc_to_uv(rec["basis_odd"], "odd")),
        }
    for name in ("dims_fast_test2.json", "dims_17_24.json"):
        path = RES / name
        if not path.exists():
            continue
        data = json.loads(path.read_text())
        items = data.items() if isinstance(data, dict) else (
            (str(rec["n"]), rec) for rec in data)
        for key, rec in items:
            n = int(key)
            if n in merged:
                continue  # dims_2_16.json remains the source of record
            merged[n] = {
                "even": (rec["dim_even"], [tuple(p) for p in rec["basis_even"]]),
                "odd": (rec["dim_odd"], [tuple(p) for p in rec["basis_odd"]]),
            }
    return merged


def _rc_to_uv(basis, comp):
    """Rc to uv.
    
    Args:
        basis:
        comp:
    
    Returns:
        The computed result
    
    """
    return [tuple(to_uv(Cell(r, c), comp)) for (r, c) in basis]


def check_invariants(results):
    """Component sizes, basis membership, and conjecture agreement."""
    problems = []
    for n, res in sorted(results.items()):
        if n % 2 == 0:
            expect = {"even": n * n // 2, "odd": n * n // 2}
        else:
            expect = {"even": (n * n + 1) // 2, "odd": (n * n - 1) // 2}
        points = {"even": set(component_uv(n, "even")),
                  "odd": set(component_uv(n, "odd"))}
        for comp in ("even", "odd"):
            if n == 1 and comp == "odd":
                continue  # the odd component is empty for n=1
            dim, basis = res[comp]
            if len(points[comp]) != expect[comp]:
                problems.append(f"n={n} {comp}: size {len(points[comp])} "
                                f"!= (n^2+c)/2 = {expect[comp]}")
            bad = [p for p in basis if p not in points[comp]]
            if bad:
                problems.append(f"n={n} {comp}: basis points outside component: {bad}")
            conj = conjectures(n)[comp] if n >= 2 else None
            if conj is not None and dim != conj:
                problems.append(f"n={n} {comp}: dim {dim} != conjecture {conj}")
    return problems


def tables_auto(max_n):
    """Tables auto.
    
    Args:
        max_n:
    
    Returns:
        The computed result
    
    """
    return (HEADER + f"\\newcommand{{\\nmaxverified}}{{{max_n}}}\n")


def table_body(results):
    """Table body.
    
    Args:
        results:
    
    Returns:
        The computed result
    
    """
    lines = [
        HEADER.rstrip("\n"),
        "\\begin{tabular}{rrccccc}",
        "\\toprule",
        " & & \\multicolumn{2}{c}{component dimension} & & "
        "\\multicolumn{2}{c}{matches conj.? \\ref{conj:forms}} \\\\",
        "\\cmidrule(lr){3-4}\\cmidrule(lr){6-7}",
        "$n$ & $|C_\\mathrm{e}|$ & $C_\\mathrm{e}$ ($r{+}c$ even) & "
        "$C_\\mathrm{o}$ ($r{+}c$ odd) & total & $C_\\mathrm{e}$ & $C_\\mathrm{o}$ \\\\",
        "\\midrule",
    ]
    # n = 1: single vertex; the odd component is empty (Lemma lem:union).
    lines.append("1 & 1 & 0 & -- & 0 & -- & -- \\\\")
    for n in sorted(results):
        dim_e, _ = results[n]["even"]
        dim_o, _ = results[n]["odd"]
        total = dim_e + dim_o
        conj = conjectures(n)
        if n % 2 == 0:
            # both classes carry formula (A); one class is the transpose copy
            ok_e = "\\checkmark" if dim_e == conj["even"] else "\\textbf{no}"
            ok_o = "\\checkmark" if dim_o == conj["even"] else "\\textbf{no}"
        else:
            ok_e = "\\checkmark" if dim_e == conj["even"] else "\\textbf{no}"
            ok_o = "\\checkmark" if dim_o == conj["odd"] else "\\textbf{no}"
        lines.append(f"{n} & {n * n // 2} & {dim_e} & {dim_o} & {total} "
                     f"& {ok_e} & {ok_o} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}\n"]
    return "\n".join(lines) + "\n"


def fig_n9(results):
    """Fig n9.
    
    Args:
        results:
    
    Returns:
        The computed result
    
    """
    n = 9
    B = n - 1
    dim, basis = results[n]["even"]      # odd n: 'even' key = corner class
    assert dim == 9, (n, dim)
    lm = sorted(basis)
    assert lm == FIG_N9_LANDMARKS, (
        "fig_n9 basis disagrees with the caption in main.tex:", lm)

    rows = range(-(B // 2), B // 2 + 1)          # |u| <= floor(B/2)
    points = [(u, v) for u in rows for v in range(abs(u), B - abs(u) + 1)]
    assert len(points) == 41, len(points)        # (n^2+1)/2 for n=9

    lines = [HEADER.rstrip("\n"),
             "\\begin{tikzpicture}[scale=0.55,every node/.style={inner sep=0}]"]
    for u in rows:
        lines.append(f"\\draw ({abs(u)},{u}) -- ({B - abs(u)},{u});")
    for v in range(B + 1):
        m = min(v, B - v)
        lines.append(f"\\draw ({v},{...}) -- ({v},{m});")
    for (u, v) in points:
        lines.append(f"\\fill[black] ({v},{u}) circle (2.4pt);")
    for (u, v) in lm:
        lines.append(f"\\fill[red] ({v},{u}) circle (3.4pt);")
    lines.append("\\end{tikzpicture}")
    return "\n".join(lines) + "\n"


def main():
    """Entry point — parse arguments and run the main computation.
    
    Returns:
        The computed result
    
    """
    results = load_results()
    max_n = max(results)

    problems = check_invariants(results)
    for p in problems:
        print("PROBLEM:", p)

    (PAPER / "tables_auto.tex").write_text(tables_auto(max_n), encoding="utf-8")
    (PAPER / "tables_auto_body.tex").write_text(table_body(results), encoding="utf-8")
    (PAPER / "fig_n9.tex").write_text(fig_n9(results), encoding="utf-8")
    print(f"wrote tables_auto.tex (nmaxverified={max_n}), "
          f"tables_auto_body.tex ({max(results) - 1 + 1} data rows + n=1), "
          f"fig_n9.tex from dims_2_16.json n=9")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
